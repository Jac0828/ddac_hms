const LanguageContext = createContext<LanguageContextType | undefined>(undefined);

export const LanguageProvider: React.FC<{ children: ReactNode }> = ({ children }) => {
  const [language, setLanguageState] = useState<Language>(() => {
    const stored = localStorage.getItem('language') as Language;
    const validLanguages: Language[] = ['en', 'zh', 'ja', 'ko', 'fr', 'de', 'es', 'pt', 'ar', 'th'];
    return stored && validLanguages.includes(stored) ? stored : 'en';
  });

  const setLanguage = (lang: Language) => {
    setLanguageState(lang);
    localStorage.setItem('language', lang);
  };

  const t = (key: string): string => {
    const langTranslations = translations[language];
    if (langTranslations && langTranslations[key]) {
      return langTranslations[key];
    }
    // Fallback to English if translation not found
    const englishTranslation = translations.en[key];
    if (englishTranslation) {
      return englishTranslation;
    }
    // If still not found, return empty string so fallback text can be used
    return '';
  };

  // Helper function to get role name translation
  const getRoleName = (role: string): string => {
    const roleKey = `roles.name.${role.toLowerCase()}`;
    const translated = t(roleKey);
    // If translation not found, return the original role name
    return translated || role;
  };

  return (
    <LanguageContext.Provider value={{ language, setLanguage, t, getRoleName }}>
      {children}
    </LanguageContext.Provider>
  );
};

export const useLanguage = () => {
  const context = useContext(LanguageContext);
  if (!context) {
    throw new Error('useLanguage must be used within LanguageProvider');
  }
  return context;
};

